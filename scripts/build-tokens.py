#!/usr/bin/env python3
"""Build every stylesheet from tokens/adaptive.tokens.json, and guard against hand-written colour.

    scripts/build-tokens.py                write every output
    scripts/build-tokens.py --check        change nothing; fail when an output is stale or a file
                                           spells out a colour it is not allowed to (verify-all --quick)
    scripts/build-tokens.py --rebaseline   after moving a file onto tokens: record the lower counts
    scripts/build-tokens.py --show         print the resolved palette

Outputs:
  *.src.css -> *.css next to it (shell, Files, Home, Agent Office, the TV page, the GTK apps)
  theme/Adaptive (the session GTK theme, through scripts/build-adaptive-theme.py)
  docs/DESIGN_SYSTEM.md, the palette tables between the tokens:begin / tokens:end marks

The guard: a *.src.css file may not contain a colour value at all. Any other source file may hold
at most the number recorded for it in tokens/handwritten-colours.json, which only ever goes down;
a file that is not listed may hold none. Artwork and data (icons, the pixel-art office, terminal
schemes) are listed with their reason under "exempt" in the token file.
"""

import importlib.util
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import adaptive_tokens as T  # noqa: E402

REPO = T.REPO
GUIDE = REPO / "docs" / "DESIGN_SYSTEM.md"
BEGIN, END = "<!-- tokens:begin -->", "<!-- tokens:end -->"


def theme_module():
    spec = importlib.util.spec_from_file_location("build_adaptive_theme", REPO / "scripts" / "build-adaptive-theme.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def guide_block(tokens):
    raw = tokens.raw
    lines = [BEGIN, "<!-- Generated by scripts/build-tokens.py from tokens/adaptive.tokens.json. Do not edit between the marks. -->", "",
             "### Neutral ramp", "",
             f'One hue (OKLCH hue {raw["ramp"]["hue"]}, chroma {raw["ramp"]["chroma"]}) at twelve lightness steps.', "",
             "| Step | Value | Lightness |", "|---|---|---:|"]
    for i, value in enumerate(tokens.ramp):
        lines.append(f'| `n{i}` | `{value}` | {raw["ramp"]["lightness"][i]} |')
    lines += ["", "### Hues", "", "| Name | Value |", "|---|---|"]
    lines += [f"| `{name}` | `{value}` |" for name, value in raw["hue"].items()]
    lines += ["", "### Alpha scale", "",
              "A colour is only ever used at full strength or at one of: "
              + ", ".join(f"{a}%" for a in tokens.alphas) + ".", "",
              "### Roles", "", "| Role | Points at | Value |", "|---|---|---|"]
    for name, alias in raw["color"].items():
        if not name.startswith("_"):
            lines.append(f"| `{name}` | `{alias}` | `{tokens.css(name)}` |")
    scheme = tokens.terminal()
    names = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
    lines += ["", "### Terminal", "",
              f'Ground `{scheme["background"]}`, text `{scheme["foreground"]}`, cursor `{scheme["cursor"]}`. '
              "Applied by `scripts/install-terminal.py`.", "", "| ANSI | Normal | Bright |", "|---|---|---|"]
    lines += [f'| {name} | `{scheme["ansi"][i]}` | `{scheme["ansi"][i + 8]}` |' for i, name in enumerate(names)]
    lines += ["", "### Gradient", "", f'`aurora`: `{tokens.value("gradient.aurora")}`. Mario thinking or answering, nothing else.',
              "", "### Size and motion", "", "| Token | Value |", "|---|---|"]
    lines += [f"| `radius.{k}` | {v}px |" for k, v in raw["radius"].items()]
    lines += [f"| `space.{k}` | {v}px |" for k, v in raw["spacing"].items()]
    lines += [f'| `motion.{k}` | {v}{"ms" if k.endswith(".ms") else ""} |' for k, v in raw["motion"].items()]
    lines += ["", END]
    return "\n".join(lines)


def outputs(tokens):
    """{path: text} for everything this script owns."""
    result = {T.output_for(source): T.render(tokens, source) for source in T.sources()}
    result.update(theme_module().outputs(tokens))
    if GUIDE.exists():
        text = GUIDE.read_text(encoding="utf-8")
        if BEGIN in text and END in text:
            head, rest = text.split(BEGIN, 1)
            result[GUIDE] = head + guide_block(tokens) + rest.split(END, 1)[1]
    return result


def read_baseline():
    try:
        return json.loads(T.BASELINE.read_text(encoding="utf-8"))["files"]
    except (OSError, ValueError, KeyError):
        return {}


def write_baseline(found):
    T.BASELINE.write_text(json.dumps({
        "_about": "Colour values still written by hand, per file. scripts/build-tokens.py --check lets a "
                  "count go down, never up; done is an empty list. Lower it with --rebaseline.",
        "files": dict(sorted(found.items())),
    }, indent=2) + "\n", encoding="utf-8")


def check(tokens):
    problems = []
    for path, text in outputs(tokens).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            problems.append(f"stale: {path.relative_to(REPO)} (run scripts/build-tokens.py)")
    for source in T.sources():
        count = T.count_colours(source)
        if count:
            problems.append(f"{source.relative_to(REPO)}: {count} colour value(s) written by hand; name a token instead")
    baseline, found = read_baseline(), T.handwritten(tokens)
    for path, count in sorted(found.items()):
        if path.endswith(T.SOURCE_SUFFIX):
            continue
        allowed = baseline.get(path, 0)
        if count > allowed:
            problems.append(f"{path}: {count} hand-written colour value(s), allowed {allowed}. "
                            "Use tokens (a *.src.css, or adaptive_tokens.load() in Python)")
    remaining = sum(count for path, count in found.items() if not path.endswith(T.SOURCE_SUFFIX))
    for problem in problems:
        print(f"FAIL {problem}")
    print(f"{'FAIL' if problems else 'OK  '} tokens: {len(T.sources())} stylesheets generated, "
          f"{remaining} hand-written colour values left in {len(found)} files")
    return 1 if problems else 0


def main(argv):
    try:
        tokens = T.load()
        if "--show" in argv:
            for name, (value, alpha) in tokens.colors.items():
                print(f"{name:<18} {value}" + (f" / {alpha}%" if alpha is not None else ""))
            return 0
        if "--check" in argv:
            return check(tokens)
        if "--rebaseline" in argv:
            found = {p: c for p, c in T.handwritten(tokens).items() if not p.endswith(T.SOURCE_SUFFIX)}
            write_baseline(found)
            print(f"Recorded {sum(found.values())} hand-written colour values in {len(found)} files")
            return 0
        written = 0
        for path, text in outputs(tokens).items():
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
                print(f"  wrote {path.relative_to(REPO)}")
                written += 1
        theme_module().link(verbose=False)
        print(f"Tokens: {written} file(s) updated, {len(outputs(tokens)) - written} already current")
        return 0
    except T.TokenError as error:
        print(f"FAIL tokens: {error}")
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
